"""Refit repeatedly, and never let a model trade a day it has seen.

A single train/test split answers one question badly. It says how a
strategy fitted on one arbitrary period did on one other arbitrary
period, and the answer moves a great deal with where the cut was made —
slide it six months and a discovery becomes a dud, which is a fact about
the cut and not about the strategy. Walk-forward refits repeatedly and
always trades forward, so every reported trade was generated by a model
that had not seen the day it traded.

Training expands and never rolls. Each refit sees ALL history to that
point, because the alternative — a fixed-length window sliding forward —
quietly drops 2008 out of the training set somewhere around 2018, and a
model refitted in 2022 on a rolling ten years has never been shown a
credit crisis. The sample was chosen to contain the episodes that break
things; a window that discards them gives that back.

The trap this file exists to close is subtler than lookahead, and it is
why the result object is shaped the way it is. A walk-forward produces
two curves per fold — the one the model was fitted on and the one it
traded blind — and they sit one attribute apart. Nothing stops somebody
computing a Sharpe on the wrong one, and the wrong one is always the
better-looking. So there is exactly one stitched curve on the result,
`oos_equity`, assembled only from days each model traded blind; the
fitted curves live behind `in_sample_curves()`, are never stitched, and
`result.equity` raises rather than resolving to something plausible.

They are never stitched for a reason worth stating once. Under expanding
training the in-sample windows OVERLAP — every fold's training set
contains every earlier fold's — so a "continuous in-sample curve" would
compound 2008 once for each refit that had seen it. There is no such
series. Returning the folds separately makes it impossible to build one
by accident.

Two other things this module insists on.

**It never imports a strategy.** Fitting and running arrive as
callables, which is what makes the whole thing testable with a stub that
returns a constant, and what stops the validation layer growing opinions
about what a strategy is.

**Every configuration evaluated is written to `metrics.TrialCounter`.**
A walk-forward that tries five parameter sets at each of fifteen refits
has searched five configurations, not one, and the naive count a reader
would assume — "we ran one backtest" — understates the search by the
whole factor that the deflated Sharpe exists to correct for. A `fit` that
returns a bare mapping is taken at its word as one configuration; a `fit`
that searched and wants to say so returns a `FitOutcome` carrying every
candidate it looked at.
"""

